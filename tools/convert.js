// Converts an unpacked dc-runtime prototype (logic.js + markup.html) into the Angular user app files.
// usage: node tools/convert.js <unpackDir> client/src/app/user   (see CLAUDE.md "Regenerating the user app")
const fs = require('fs'), path = require('path');
const [, , src, out] = process.argv;
fs.mkdirSync(out, { recursive: true });
const logicSrc = fs.readFileSync(path.join(src, 'logic.js'), 'utf8');
const markup = fs.readFileSync(path.join(src, 'markup.html'), 'utf8');

// ---------- logic ----------
let logic = logicSrc
  .replace(/^\s*class Component extends DCLogic \{/m,
`export class UserAppLogic {
  version = 0;
  props: any = {};
  state: any = {};
  pendingCallbacks: Array<() => void> = [];
  setState(p: any, cb?: () => void): void {
    const patch = typeof p === 'function' ? p(this.state) : p;
    if (cb) this.pendingCallbacks.push(cb);
    if (!patch) return;
    this.state = Object.assign({}, this.state, patch);
    this.version++;
  }
  forceUpdate(): void { this.version++; }`)
  .replace(/React\.createElement/g, 'h')
  .replace(/React\.createRef\(\)/g, 'ref()')
  .replace(/\bsuper\(props\);/, 'this.props = props;');
if (/React\./.test(logic)) throw new Error('unconverted React usage: ' + logic.match(/.{40}React\..{40}/)[0]);
if (/DCLogic/.test(logic)) throw new Error('DCLogic left');
logic = `// @ts-nocheck
// GENERATED by scratch convert.js from the Beyond Infinity prototype (dc-runtime class component).
// Behaviour is kept as-is; React element creation is replaced by h()/ref() from ./user-h.ts.
import { h, ref } from './user-h';
` + logic.trim() + '\n';
fs.writeFileSync(path.join(out, 'user-logic.ts'), logic);

// Methods that build elements, used to decide which template values are elements (rendered as HTML).
const elemMethods = new Set();
const methodRe = /^\s{2}([a-zA-Z_]\w*)\s*\([^)]*\)\s*\{/gm;
let mm; const starts = [];
while ((mm = methodRe.exec(logicSrc))) starts.push([mm[1], mm.index]);
starts.forEach(([name, i], k) => {
  const body = logicSrc.slice(i, k + 1 < starts.length ? starts[k + 1][1] : logicSrc.length);
  if (/return\s+(React\.createElement|e\(|h\()/.test(body) || /^\s{2}\w+\([^)]*\)\s*\{\s*return React\.createElement/.test(body)) elemMethods.add(name);
});
const elemRhs = new RegExp('React\\.createElement\\(|\\be\\(\'|\\bhb\\(|this\\.(' + [...elemMethods].join('|') + ')\\(');
function isElemKey(key) {
  const re = new RegExp('[{,\\s]' + key + '\\s*:\\s*([^\\n]{0,240})', 'g');
  let m; while ((m = re.exec(logicSrc))) { if (elemRhs.test(m[1].slice(0, 160))) return true; }
  return false;
}

// ---------- markup ----------
const helmet = markup.match(/<helmet>([\s\S]*?)<\/helmet>/)[1];
const styles = [...helmet.matchAll(/<style>([\s\S]*?)<\/style>/g)].map(m => m[1]);
const fontCss = styles.find(s => s.includes('@font-face')) || '';
const appCss = styles.find(s => s.includes('@keyframes')) || '';

const innerOpenIdx = markup.indexOf('<div style="width:402px;height:874px;');
const innerOpenEnd = markup.indexOf('>', innerOpenIdx) + 1;
const importClose = markup.lastIndexOf('</x-import>');
const lastDiv = markup.lastIndexOf('</div>', importClose);
let innerStyle = markup.slice(innerOpenIdx, innerOpenEnd).match(/style="([^"]*)"/)[1]
  .replace('width:402px;height:874px;', 'width:100%;height:100%;');
let body = markup.slice(innerOpenEnd, lastDiv);

const scopes = [];
const usedElemKeys = new Set();
function scoped(p) {
  p = p.trim();
  if (p === 'true' || p === 'false' || p === 'null') return p;
  const first = p.split('.')[0];
  for (const s of scopes) if (s === first) return p;
  return 'vm.' + p;
}
const interpOnly = /^\{\{\s*([^}]+?)\s*\}\}$/;
const escText = t => t.replace(/@/g, '&#64;').replace(/\{/g, '&#123;').replace(/\}/g, '&#125;');
const EVENTS = { click: 'click', input: 'input', blur: 'blur', 'key-down': 'keydown', scroll: 'scroll',
  'pointer-move': 'pointermove', 'pointer-leave': 'pointerleave', 'pointer-up': 'pointerup', 'pointer-down': 'pointerdown', 'pointer-cancel': 'pointercancel' };

function convertTag(tag) {
  if (/^<sc-if\b/.test(tag)) { const v = tag.match(/value="\{\{\s*([^}]+?)\s*\}\}"/)[1]; scopes.unshift('@if'); return '@if (' + scoped(v) + ') {'; }
  if (/^<sc-for\b/.test(tag)) {
    const l = tag.match(/list="\{\{\s*([^}]+?)\s*\}\}"/)[1], as = tag.match(/as="([^"]+)"/)[1];
    const r = '@for (' + as + ' of ' + scoped(l) + '; track $index) {'; scopes.unshift(as); return r;
  }
  if (/^<\/sc-(if|for)>/.test(tag)) { scopes.shift(); return '}'; }
  if (/^<\//.test(tag) || /^<!/.test(tag)) return tag;
  const m = tag.match(/^<([a-zA-Z][\w-]*)([\s\S]*?)(\/?)>$/);
  if (!m) throw new Error('bad tag ' + tag);
  const [, name, attrStr, selfClose] = m;
  const isFile = /type="file"/.test(attrStr);
  const attrs = [];
  const attrRe = /([^\s=]+)(?:="([^"]*)")?/g; let a;
  while ((a = attrRe.exec(attrStr))) {
    let [, an, av] = a;
    if (an.startsWith('hint-')) continue;
    if (an === 'ref') { attrs.push('data-ref="' + av.match(interpOnly)[1] + '"'); continue; }
    if (an === 'sc-camel-view-box') { attrs.push('viewBox="' + av + '"'); continue; }
    const ev = an.match(/^sc-camel-on-(.+)$/);
    if (ev) {
      let evName = ev[1] === 'change' ? (isFile ? 'change' : 'input') : EVENTS[ev[1]];
      if (!evName) throw new Error('unknown event ' + an);
      // Controlled inputs: sync bindings right after typing so a later reset to '' is detected.
      const sync = evName === 'input' || evName === 'change' ? '; uSync()' : '';
      attrs.push('(' + evName + ')="' + scoped(av.match(interpOnly)[1]) + '($event)' + sync + '"'); continue;
    }
    if (av === undefined) { attrs.push(an); continue; }
    if (!av.includes('{{')) { attrs.push(an + '="' + av + '"'); continue; }
    if (an === 'style' || an === 'placeholder') { attrs.push(an + '="' + av.replace(/\{\{\s*([^}]+?)\s*\}\}/g, (_, p) => '{{ ' + scoped(p) + ' }}') + '"'); continue; }
    const only = av.match(interpOnly);
    if (only) { attrs.push((an === 'value' ? '[value]' : '[attr.' + an + ']') + '="' + scoped(only[1]) + '"'); continue; }
    const parts = av.split(/(\{\{\s*[^}]+?\s*\}\})/).filter(Boolean).map(s => { const o = s.match(interpOnly); return o ? '(' + scoped(o[1]) + ')' : "'" + s.replace(/'/g, "\\'") + "'"; });
    attrs.push('[attr.' + an + ']="' + parts.join(' + ') + '"');
  }
  return '<' + name + (attrs.length ? ' ' + attrs.join(' ') : '') + selfClose + '>';
}
function convertText(t) {
  return t.split(/(\{\{\s*[^}]+?\s*\}\})/).map(s => {
    const o = s.match(interpOnly);
    if (!o) return escText(s);
    const p = o[1].trim(), key = p.split('.').pop();
    // Inside SVG an HTML span is not rendered (the prototype loses these labels); use plain text.
    if (svgDepth > 0) return '{{ uShow(' + scoped(p) + ') ? ' + scoped(p) + " : '' }}";
    if (isElemKey(key)) { usedElemKeys.add(p); return '<span style="display:contents" [innerHTML]="uNode(' + scoped(p) + ')"></span>'; }
    return '@if (uShow(' + scoped(p) + ')) {<span class="sc-interp">{{ ' + scoped(p) + ' }}</span>}';
  }).join('');
}
let html = '', svgDepth = 0;
const tokRe = /<[^>]+>|[^<]+/g; let tk;
while ((tk = tokRe.exec(body))) {
  const s = tk[0];
  if (/^<svg\b/.test(s) && !/\/>$/.test(s)) svgDepth++;
  if (/^<\/svg>/.test(s)) svgDepth--;
  html += s[0] === '<' ? convertTag(s) : convertText(s);
}
if (svgDepth) throw new Error('unbalanced svg');
if (scopes.length) throw new Error('unbalanced sc blocks');

html = html.replace(/height:874px;/g, 'min-height:100%;');
const tpl = `<div class="u-root" data-ref="rootRef">
  <div class="u-screen" data-ref="screenRef">
    <div style="${innerStyle}">${html}</div>
  </div>
</div>
`;
fs.writeFileSync(path.join(out, 'user-app.html'), tpl);

// ---------- css ----------
const interFaces = (fontCss.match(/@font-face\s*\{[^}]*\}/g) || []).filter(f => /'Inter'/.test(f));
const fontFiles = [];
const interCss = interFaces.map(f => f.replace(/url\("([^"]+)"\)/, (_, u) => { fontFiles.push(u); return 'url("/assets/fonts/' + u + '")'; })).join('\n');
const css = appCss
  .replace(/^body\{[^}]*\}\s*$/m, '')
  .replace(/^a\{/m, '.u-root a{').replace(/\}a:hover\{/, '}.u-root a:hover{')
  .replace(/^input::placeholder/m, '.u-root input::placeholder').trim();
fs.writeFileSync(path.join(out, 'user-app.css'), `/* GENERATED from the Beyond Infinity prototype styles. */
${interCss}
${css}

/* Responsive shell (replaces the prototype's phone frame). The screen keeps the 402px design width;
   the component zooms it to the phone's width so every screen matches the prototype on any phone. */
.u-root { width: 100%; height: 100dvh; overflow: hidden; display: flex; justify-content: center; background: #050506; }
.u-screen { position: relative; flex: none; width: 402px; height: 100dvh; overflow: hidden; background: #0A0A0A; }
@media (min-width: 601px) { .u-screen { box-shadow: 0 0 0 1px rgba(255,255,255,.08), 0 30px 80px rgba(0,0,0,.6); } }
/* The admin's global reset uses border-box; the prototype screens are laid out with the browser default. */
.u-screen *, .u-screen *::before, .u-screen *::after { box-sizing: content-box; }
`);
fs.writeFileSync(path.join(src, 'fonts.txt'), fontFiles.join('\n'));
console.log('elem methods:', [...elemMethods].join(','));
console.log('elem keys used:', [...usedElemKeys].join(','));
console.log('html', tpl.length, 'logic', logic.length, 'fonts', fontFiles.length);
